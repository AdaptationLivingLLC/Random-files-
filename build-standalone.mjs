import {readFile,writeFile} from 'node:fs/promises';
const read=p=>readFile(new URL(p,import.meta.url),'utf8');
const role=JSON.parse(await read('./package.json')).veildrop.role;
let html=await read('./public/index.html');
const css=await read('./public/style.css');
const module=(source,names)=>`(()=>{${source.replace(/^import .*;\n/gm,'').replace(/export /g,'')}\nreturn {${names}};})()`;
const codec=module(await read('./public/codec.js'),'b64,wordCount,decrypt,writePayload,readPayload');
const veil=module(await read('./public/veil.js'),'newDescriptor,parseDescriptor,sealVeil,prepareVeil,openVeil,validateVeil,encode64,decode64');
const common=module(await read('./public/common.js'),'$,standalone,ui,notify,api,drawArt,imageFrom,loadKey,initTheme');
const app=(await read('./public/app.js')).replace(/^import .*;\n/gm,'');
const script=`const {b64,wordCount,decrypt,writePayload,readPayload}=${codec};\nconst {newDescriptor,parseDescriptor,sealVeil,prepareVeil,openVeil,validateVeil,encode64,decode64}=${veil};\nconst {$,standalone,ui,notify,api,drawArt,imageFrom,loadKey,initTheme}=${common};\n${app}`;
new Function(script);
html=html.replace('<link rel="stylesheet" href="/style.css">',()=>`<style>${css}</style>`).replace('<script type="module" src="/app.js"></script>',()=>`<script type="module">${script}</script>`).replace('<body>','<body data-standalone="true">');
const name=`VeilDrop-${role==='encoder'?'Encoder':'Decoder'}-Offline.html`;
await writeFile(new URL('./public/'+name,import.meta.url),html);console.log(name+' built');
